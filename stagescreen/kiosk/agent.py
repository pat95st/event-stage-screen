"""Kiosk agent: runs inside the sway session and drives the HDMI outputs.

Every few seconds it

1. fetches the desired output configuration from the web service,
2. applies video modes, rotation and layout with ``wlr-randr``,
3. keeps exactly one Chromium kiosk window per enabled, connected output
   (restarting it if it crashes, or when a monitor is plugged in again),
4. reports the detected outputs and browser state back to the web service.

The web service and the agent run as the same system user and share the
kiosk token stored in ``<data>/kiosk.token``.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import signal
import subprocess
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .randr import Randr, logical_width

log = logging.getLogger("ess.kiosk")

CHROMIUM_FLAGS = [
    "--ozone-platform=wayland",
    "--no-first-run", "--noerrdialogs", "--disable-infobars", "--disable-session-crashed-bubble",
    "--password-store=basic", "--autoplay-policy=no-user-gesture-required",
    "--disable-features=Translate,TranslateUI,WebRtcHideLocalIpsWithMdns,HardwareMediaKeyHandling",
    "--disable-pinch", "--overscroll-history-navigation=0", "--check-for-update-interval=31536000",
    "--enable-gpu-rasterization", "--ignore-gpu-blocklist",
]


def chromium_binary() -> str | None:
    for name in ("chromium", "chromium-browser"):
        path = shutil.which(name)
        if path:
            return path
    return None


def sway_rules(connectors: dict[int, str]) -> str:
    """sway rules placing each output's browser window full screen on its connector.

    In ``--app`` mode Chromium derives the Wayland app_id from the URL
    (e.g. ``chromium-127.0.0.1__render_1-Default``); ``--class`` has no effect
    there, so the rule matches the render path.
    """
    lines = ["# Generated by event-stage-screen – do not edit"]
    for n, name in sorted(connectors.items()):
        lines.append(f'for_window [app_id="__render_{n}-"] move container to output "{name}", fullscreen enable')
    return "\n".join(lines) + "\n"


@dataclass
class Browser:
    output_id: int
    connector: str
    url: str
    proc: Any = None
    restarts: int = 0
    next_start: float = 0.0
    backoff: float = 2.0

    def running(self) -> bool:
        return self.proc is not None and self.proc.poll() is None


@dataclass
class KioskAgent:
    base_url: str
    token: str
    randr: Randr = field(default_factory=Randr)
    runtime_dir: Path = field(default_factory=lambda: Path(os.environ.get("XDG_RUNTIME_DIR", "/tmp")))
    sway_dir: Path | None = None
    spawn: Callable[[list[str]], Any] | None = None
    http: Callable[[str, dict | None], dict] | None = None
    clock: Callable[[], float] = time.monotonic
    browsers: dict[int, Browser] = field(default_factory=dict)
    connectors: dict[int, str] = field(default_factory=dict)
    failed_plans: dict[str, tuple[tuple, float]] = field(default_factory=dict)
    last_error: str | None = None

    # ------------------------------------------------------------------ I/O
    def _http(self, path: str, data: dict | None = None) -> dict:
        if self.http:
            return self.http(path, data)
        body = json.dumps(data).encode() if data is not None else None
        req = urllib.request.Request(self.base_url + path, data=body, method="POST" if body else "GET",
                                     headers={"X-ESS-Kiosk": self.token, "Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=5) as res:
            return json.loads(res.read() or b"{}")

    def _spawn(self, cmd: list[str]) -> Any:
        if self.spawn:
            return self.spawn(cmd)
        return subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)

    # ------------------------------------------------------------------ one cycle
    def step(self) -> None:
        try:
            config = self._http("/api/kiosk/config").get("result") or {}
        except (urllib.error.URLError, OSError, ValueError) as exc:
            if self.last_error != str(exc):
                log.warning("Web service not reachable: %s", exc)
                self.last_error = str(exc)
            self.supervise_browsers({o: b.connector for o, b in self.browsers.items()}, {})
            return
        self.last_error = None
        if config.get("token"):
            self.token = config["token"]
        desired = {o["id"]: o for o in config.get("outputs") or []}
        outputs = {o["name"]: o for o in self.randr.outputs()}

        self.update_sway({n: d["connector"] for n, d in desired.items()})
        self.apply_outputs(desired, outputs)
        outputs = {o["name"]: o for o in self.randr.outputs()}

        active = {n: d["connector"] for n, d in desired.items() if d.get("enabled") and d["connector"] in outputs
                  and outputs[d["connector"]].get("modes")}
        urls = {n: d["url"] for n, d in desired.items()}
        self.supervise_browsers(active, urls)
        self.report(list(outputs.values()))

    def apply_outputs(self, desired: dict[int, dict], outputs: dict[str, dict]) -> None:
        x = 0
        for n in sorted(desired):
            d = desired[n]
            out = outputs.get(d["connector"])
            if out is None or not out.get("modes"):
                continue
            args = self.randr.plan(out, d, x)
            if args:
                signature = tuple(args)
                failed = self.failed_plans.get(d["connector"])
                if failed and failed[0] == signature and self.clock() - failed[1] < 60:
                    pass  # do not hammer the compositor with a mode it rejected
                else:
                    ok, _ = self.randr.apply(args)
                    if ok:
                        self.failed_plans.pop(d["connector"], None)
                    else:
                        self.failed_plans[d["connector"]] = (signature, self.clock())
            if d.get("enabled"):
                x += logical_width(out) or (d.get("mode") or {}).get("width", 1920)

    def update_sway(self, connectors: dict[int, str]) -> None:
        if connectors == self.connectors or self.sway_dir is None:
            self.connectors = connectors
            return
        self.connectors = connectors
        (self.sway_dir / "rules").write_text(sway_rules(connectors))
        if self.spawn is None and shutil.which("swaymsg"):
            subprocess.run(["swaymsg", "reload"], capture_output=True, timeout=10)
        # window rules apply when a window appears: restart the browsers
        for b in self.browsers.values():
            self.stop(b)

    # ------------------------------------------------------------------ browsers
    def supervise_browsers(self, active: dict[int, str], urls: dict[int, str]) -> None:
        for n in list(self.browsers):
            b = self.browsers[n]
            if n not in active or active[n] != b.connector or (urls.get(n) and urls[n] != b.url):
                self.stop(b)
                del self.browsers[n]
        for n, connector in active.items():
            b = self.browsers.get(n)
            if b is None:
                b = self.browsers[n] = Browser(n, connector, urls.get(n, ""))
            if not b.running():
                if b.proc is not None:
                    b.restarts += 1
                    b.next_start = self.clock() + b.backoff
                    b.backoff = min(30.0, b.backoff * 2)
                    log.warning("Browser for output %d exited – restarting in %.0f s", n, b.next_start - self.clock())
                    b.proc = None
                if self.clock() >= b.next_start:
                    self.start(b)
            elif b.backoff > 2 and self.clock() - b.next_start > 60:
                b.backoff = 2.0  # stable again

    def start(self, b: Browser) -> None:
        binary = chromium_binary() if self.spawn is None else "chromium"
        if not binary:
            log.error("Chromium is not installed")
            return
        profile = self.runtime_dir / f"ess-chromium-{b.output_id}"
        shutil.rmtree(profile, ignore_errors=True)  # fresh profile: no crash bubbles, no stale locks
        url = f"{b.url}?k={self.token}"
        extra = os.environ.get("ESS_CHROMIUM_FLAGS", "").split()
        cmd = [binary, *CHROMIUM_FLAGS, *extra, f"--user-data-dir={profile}", f"--app={url}"]
        log.info("Starting browser for output %d on %s", b.output_id, b.connector)
        b.proc = self._spawn(cmd)

    def stop(self, b: Browser) -> None:
        if b.running():
            b.proc.terminate()
            try:
                b.proc.wait(timeout=5)
            except Exception:
                b.proc.kill()
        b.proc = None

    # ------------------------------------------------------------------ report
    def report(self, outputs: list[dict]) -> None:
        data = {
            "outputs": outputs,
            "browsers": {str(n): {"connector": b.connector, "running": b.running(), "restarts": b.restarts}
                         for n, b in self.browsers.items()},
            "chromium": bool(chromium_binary()) if self.spawn is None else True,
        }
        try:
            self._http("/api/kiosk/report", data)
        except (urllib.error.URLError, OSError, ValueError):
            pass

    def shutdown(self) -> None:
        for b in self.browsers.values():
            self.stop(b)


def main() -> None:
    logging.basicConfig(level=os.environ.get("ESS_LOG_LEVEL", "INFO"),
                        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s")
    data_dir = Path(os.environ.get("ESS_DATA_DIR", "./data")).resolve()
    port = int(os.environ.get("ESS_PORT", "8080"))
    token_file = data_dir / "kiosk.token"
    sway_dir = os.environ.get("ESS_SWAY_DIR")
    while not token_file.exists():
        log.info("Waiting for %s (is the web service running?)", token_file)
        time.sleep(2)
    agent = KioskAgent(base_url=f"http://127.0.0.1:{port}", token=token_file.read_text().strip(),
                       sway_dir=Path(sway_dir) if sway_dir else None)
    running = True

    def stop(*_: Any) -> None:
        nonlocal running
        running = False

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    log.info("Kiosk agent started")
    try:
        while running:
            try:
                agent.step()
            except Exception:  # never let the display loop die
                log.exception("Kiosk step failed")
            time.sleep(2)
    finally:
        agent.shutdown()
